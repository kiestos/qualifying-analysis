"""The domain model: plain data shared by every layer.

No imports from the rest of the package and no I/O. The loader translates the raw file
into ``Lap`` objects; the rules produce ``DriverResult`` objects; the CLI only displays them.
"""

from __future__ import annotations

from dataclasses import dataclass

# Qualifying segments in order (the `qs` field). Q1-Q3 are "segments"; the whole of
# qualifying is the "session" (spec glossary).
SEGMENTS = ("Q1", "Q2", "Q3")

# Why a segment has or lacks a time (REQ-SEG-4).
TIMED = "timed"
NO_TIME = "no time set"
NOT_REACHED = "did not take part"


@dataclass(frozen=True)
class Lap:
    """One lap as recorded in the timing data. Missing values are ``None``."""

    drv: str
    team: str | None
    lap: int | None
    qs: str
    time: float | None
    s1: float | None
    s2: float | None
    s3: float | None
    sesT: float | None       # session time when the lap ended
    pin: float | None        # pit-in time, set on in-laps
    pout: float | None       # pit-out time, set on out-laps
    deleted: bool | None     # from the `del` field
    status: str              # every track-status code seen during the lap, e.g. "125"
    ff1g: bool | None        # lap generated by FastF1 rather than timed


@dataclass(frozen=True)
class SegmentResult:
    """A driver's outcome in one segment."""

    time: float | None       # best valid lap in the segment
    rank: int | None         # among drivers with a time in the segment
    gap: float | None        # to the fastest time in the segment
    status: str              # TIMED, NO_TIME or NOT_REACHED


@dataclass(frozen=True)
class DriverResult:
    """A driver's place in the final classification."""

    code: str
    team: str | None
    position: int | None     # None = not classified (NC)
    note: str | None         # placement note (REQ-CLS-8) or NC reason (REQ-CLS-6)
    furthest: str            # furthest segment reached
    segments: dict[str, SegmentResult]
