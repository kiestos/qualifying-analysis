"""REQ-LAP-*: which laps count as valid timed attempts."""

import pytest

from conftest import lap
from qualifying.laps import is_valid


def test_req_lap_1_clean_timed_lap_is_valid(load_rows):
    (only,) = load_rows([lap("AAA", "Q1", 80.0)])
    assert is_valid(only)


@pytest.mark.parametrize(
    "overrides, reason",
    [
        ({"time": None}, "no time"),
        ({"del": True}, "deleted"),
        ({"pout": 900.0}, "out-lap"),
        ({"pin": 1100.0}, "in-lap"),
        ({"status": "125"}, "red flag during the lap"),
        ({"status": "152"}, "red flag during the lap"),
        ({"ff1G": True}, "generated by FastF1"),
    ],
)
def test_req_lap_1_invalid_laps(load_rows, overrides, reason):
    row = lap("AAA", "Q1", 80.0)
    row.update(overrides)
    (only,) = load_rows([row])
    assert not is_valid(only), reason


def test_req_lap_1_yellow_flag_lap_is_still_valid(load_rows):
    (only,) = load_rows([lap("AAA", "Q1", 80.0, status="12")])
    assert is_valid(only)


def test_req_lap_1_ver_out_lap_is_not_valid(real_laps):
    # VER lap 1 has time 102.025 but is an out-lap; VER has no valid laps at all.
    ver = [l for l in real_laps if l.drv == "VER"]
    assert ver[0].time == pytest.approx(102.025)
    assert not any(is_valid(l) for l in ver)


def test_req_lap_2_deletion_comes_only_from_del(load_rows):
    # delR text alone (with an off-by-one lap number, as in the real file) doesn't delete a lap.
    kept, deleted = load_rows([
        lap("AAA", "Q1", 80.0, delR="TRACK LIMITS AT TURN 9 LAP 1"),
        lap("AAA", "Q1", 81.0, **{"del": True}),
    ])
    assert is_valid(kept)
    assert not is_valid(deleted)
